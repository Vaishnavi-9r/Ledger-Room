"""Private evidence storage adapters for invoice and receipt images.

Object keys are generated by the application and stored in PostgreSQL. Download
routes authorize the metadata row first and stream bytes through the API; this
module never produces public or signed object URLs.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath
from typing import BinaryIO, Protocol
from urllib.parse import urlsplit
from uuid import UUID

from ..core.config import get_settings

logger = logging.getLogger(__name__)
_SAFE_SEGMENT = re.compile(r"^[A-Za-z0-9._-]+$")
_EVIDENCE_PREFIXES = ("businesses/", "invoices/", "receipts/")


class EvidenceStorageError(RuntimeError):
    """Safe storage operation failure; details must not contain credentials."""


class EvidenceStorageConfigurationError(EvidenceStorageError):
    """Storage backend selection or configuration is invalid."""


class EvidenceObjectNotFoundError(EvidenceStorageError):
    """The requested object is not present."""


@dataclass(frozen=True)
class EvidenceObjectInfo:
    key: str
    last_modified: datetime


class EvidenceStorage(Protocol):
    provider: str

    def put(self, key: str, contents: bytes, content_type: str) -> None: ...
    def open(self, key: str) -> BinaryIO: ...
    def delete(self, key: str) -> None: ...
    def list_objects(self, prefixes: tuple[str, ...] = _EVIDENCE_PREFIXES) -> list[EvidenceObjectInfo]: ...


def validate_object_key(key: str) -> str:
    """Accept only canonical relative POSIX object keys; reject traversal."""
    if not isinstance(key, str) or not key or "\\" in key or "\x00" in key:
        raise EvidenceStorageError("Evidence object key is invalid.")
    path = PurePosixPath(key)
    if path.is_absolute() or path.as_posix() != key or any(part in {"", ".", ".."} for part in path.parts):
        raise EvidenceStorageError("Evidence object key is invalid.")
    if any(not _SAFE_SEGMENT.fullmatch(part) for part in path.parts):
        raise EvidenceStorageError("Evidence object key is invalid.")
    if len(key) > 1024:
        raise EvidenceStorageError("Evidence object key is invalid.")
    return key


def build_evidence_key(business_id: UUID, category: str, evidence_id: UUID, extension: str) -> str:
    if category not in {"invoices", "receipts"} or extension not in {"jpg", "jpeg", "png"}:
        raise EvidenceStorageError("Evidence object key cannot be generated.")
    return validate_object_key(f"businesses/{business_id}/{category}/{evidence_id}.{extension}")


def _local_root() -> Path:
    settings = get_settings()
    configured = getattr(settings, "EVIDENCE_LOCAL_ROOT", None)
    if configured:
        return Path(configured).expanduser().resolve()
    return (Path(__file__).resolve().parents[3] / "data").resolve()


class LocalEvidenceStorage:
    provider = "local"

    def __init__(self, root: Path | str | None = None) -> None:
        self.root = Path(root).expanduser().resolve() if root is not None else _local_root()

    def _path(self, key: str) -> Path:
        safe_key = validate_object_key(key)
        candidate = (self.root / Path(*PurePosixPath(safe_key).parts)).resolve()
        if candidate == self.root or self.root not in candidate.parents:
            raise EvidenceStorageError("Evidence object key is invalid.")
        return candidate

    def put(self, key: str, contents: bytes, content_type: str) -> None:
        del content_type  # Local files are served with MIME metadata from PostgreSQL.
        destination = self._path(key)
        try:
            destination.parent.mkdir(parents=True, exist_ok=True)
            with destination.open("xb") as target:
                target.write(contents)
        except FileExistsError as exc:
            raise EvidenceStorageError("Evidence object already exists.") from exc
        except OSError as exc:
            raise EvidenceStorageError("Evidence object could not be stored.") from exc

    def open(self, key: str) -> BinaryIO:
        path = self._path(key)
        try:
            if not path.is_file():
                raise EvidenceObjectNotFoundError("Evidence object was not found.")
            return path.open("rb")
        except EvidenceObjectNotFoundError:
            raise
        except OSError as exc:
            raise EvidenceStorageError("Evidence object could not be opened.") from exc

    def delete(self, key: str) -> None:
        path = self._path(key)
        try:
            path.unlink(missing_ok=True)
        except OSError as exc:
            raise EvidenceStorageError("Evidence object could not be deleted.") from exc

    def list_objects(self, prefixes: tuple[str, ...] = _EVIDENCE_PREFIXES) -> list[EvidenceObjectInfo]:
        results: list[EvidenceObjectInfo] = []
        if not self.root.exists():
            return results
        normalized_prefixes = tuple(validate_object_key(prefix.rstrip("/")) + "/" for prefix in prefixes)
        for path in self.root.rglob("*"):
            try:
                if not path.is_file() or path.is_symlink():
                    continue
                resolved = path.resolve()
                if self.root not in resolved.parents:
                    continue
                key = resolved.relative_to(self.root).as_posix()
                if not key.startswith(normalized_prefixes):
                    continue
                results.append(EvidenceObjectInfo(
                    key=validate_object_key(key),
                    last_modified=datetime.fromtimestamp(path.stat().st_mtime, timezone.utc),
                ))
            except (OSError, EvidenceStorageError):
                logger.warning("Skipped an unreadable local evidence object during inventory")
        return results


class S3EvidenceStorage:
    """S3-compatible private object storage (AWS S3, Supabase Storage, etc.)."""

    provider = "s3"

    def __init__(self, *, bucket: str, client) -> None:
        if not bucket or not _SAFE_SEGMENT.fullmatch(bucket):
            raise EvidenceStorageConfigurationError("Evidence S3 bucket configuration is invalid.")
        self.bucket = bucket
        self.client = client

    @classmethod
    def from_settings(cls) -> "S3EvidenceStorage":
        settings = get_settings()
        endpoint = settings.EVIDENCE_S3_ENDPOINT_URL
        region = settings.EVIDENCE_S3_REGION
        bucket = settings.EVIDENCE_S3_BUCKET
        access_key = settings.EVIDENCE_S3_ACCESS_KEY_ID
        secret_key = settings.EVIDENCE_S3_SECRET_ACCESS_KEY
        if not all((endpoint, region, bucket, access_key, secret_key)):
            raise EvidenceStorageConfigurationError("S3 evidence storage is not fully configured.")
        if not settings.EVIDENCE_S3_PRIVATE_BUCKET_CONFIRMED:
            raise EvidenceStorageConfigurationError("The S3 bucket must be confirmed private before use.")
        parsed = urlsplit(endpoint)
        loopback = parsed.hostname in {"localhost", "127.0.0.1", "::1"}
        if parsed.scheme != "https" and not (parsed.scheme == "http" and loopback):
            raise EvidenceStorageConfigurationError("S3 endpoint must use HTTPS except for local development.")
        if parsed.username or parsed.password or parsed.query or parsed.fragment:
            raise EvidenceStorageConfigurationError("S3 endpoint configuration is invalid.")
        try:
            import boto3
            from botocore.config import Config

            client = boto3.client(
                "s3",
                endpoint_url=endpoint,
                region_name=region,
                aws_access_key_id=access_key.get_secret_value(),
                aws_secret_access_key=secret_key.get_secret_value(),
                config=Config(signature_version="s3v4", s3={"addressing_style": "path"}),
            )
        except Exception as exc:
            raise EvidenceStorageConfigurationError("S3 evidence storage client could not be initialized.") from exc
        return cls(bucket=bucket, client=client)

    def put(self, key: str, contents: bytes, content_type: str) -> None:
        try:
            self.client.put_object(
                Bucket=self.bucket,
                Key=validate_object_key(key),
                Body=contents,
                ContentType=content_type,
                Metadata={"ledgerroom-evidence": "true"},
            )
        except Exception as exc:
            logger.error("S3 evidence upload failed exception_type=%s", type(exc).__name__)
            raise EvidenceStorageError("Evidence object could not be stored.") from exc

    def open(self, key: str) -> BinaryIO:
        try:
            response = self.client.get_object(Bucket=self.bucket, Key=validate_object_key(key))
            return response["Body"]
        except Exception as exc:
            code = getattr(getattr(exc, "response", {}), "get", lambda *_: None)("Error")
            code = code.get("Code") if isinstance(code, dict) else None
            if code in {"NoSuchKey", "NotFound", "404"}:
                raise EvidenceObjectNotFoundError("Evidence object was not found.") from exc
            logger.error("S3 evidence download failed exception_type=%s", type(exc).__name__)
            raise EvidenceStorageError("Evidence object could not be opened.") from exc

    def delete(self, key: str) -> None:
        try:
            self.client.delete_object(Bucket=self.bucket, Key=validate_object_key(key))
        except Exception as exc:
            logger.error("S3 evidence cleanup failed exception_type=%s", type(exc).__name__)
            raise EvidenceStorageError("Evidence object could not be deleted.") from exc

    def list_objects(self, prefixes: tuple[str, ...] = _EVIDENCE_PREFIXES) -> list[EvidenceObjectInfo]:
        objects: list[EvidenceObjectInfo] = []
        try:
            for prefix in prefixes:
                token = None
                while True:
                    request = {"Bucket": self.bucket, "Prefix": validate_object_key(prefix.rstrip("/")) + "/"}
                    if token:
                        request["ContinuationToken"] = token
                    page = self.client.list_objects_v2(**request)
                    for item in page.get("Contents", []):
                        key = validate_object_key(item["Key"])
                        modified = item.get("LastModified") or datetime.fromtimestamp(0, timezone.utc)
                        objects.append(EvidenceObjectInfo(key=key, last_modified=modified))
                    if not page.get("IsTruncated"):
                        break
                    token = page.get("NextContinuationToken")
                    if not token:
                        raise EvidenceStorageError("S3 evidence inventory response was incomplete.")
        except EvidenceStorageError:
            raise
        except Exception as exc:
            logger.error("S3 evidence inventory failed exception_type=%s", type(exc).__name__)
            raise EvidenceStorageError("Evidence objects could not be inventoried.") from exc
        return objects


def get_storage(provider: str | None = None) -> EvidenceStorage:
    settings = get_settings()
    selected = provider or settings.EVIDENCE_STORAGE_BACKEND
    if selected == "local":
        return LocalEvidenceStorage()
    if selected == "s3":
        return S3EvidenceStorage.from_settings()
    raise EvidenceStorageConfigurationError("Evidence storage backend selection is invalid.")


def read_evidence(provider: str, key: str) -> bytes:
    storage = get_storage(provider)
    with storage.open(key) as source:
        return source.read()


def delete_evidence(provider: str, key: str) -> None:
    get_storage(provider).delete(key)


def inventory_orphans(db, provider: str, *, retention_days: int | None = None, delete: bool = False) -> dict[str, object]:
    """Report old unreferenced objects; deletion is explicit and retention-gated."""
    from sqlalchemy import select

    from ..models import ClarificationReceipt, Invoice

    settings = get_settings()
    retention = retention_days if retention_days is not None else settings.EVIDENCE_ORPHAN_RETENTION_DAYS
    if retention < settings.EVIDENCE_ORPHAN_RETENTION_DAYS:
        raise ValueError("Cleanup retention cannot be shorter than the configured minimum.")
    references = set(db.scalars(select(Invoice.storage_key).where(
        Invoice.storage_provider == provider,
    )).all())
    references.update(db.scalars(select(ClarificationReceipt.storage_key).where(
        ClarificationReceipt.storage_provider == provider,
    )).all())
    cutoff = datetime.now(timezone.utc).timestamp() - retention * 86400
    orphan_keys = []
    removed = []
    storage = get_storage(provider)
    for item in storage.list_objects():
        if item.key in references or item.last_modified.timestamp() > cutoff:
            continue
        orphan_keys.append(item.key)
        if delete:
            storage.delete(item.key)
            removed.append(item.key)
    return {
        "provider": provider,
        "retention_days": retention,
        "delete_requested": delete,
        "orphan_count": len(orphan_keys),
        "removed_count": len(removed),
        "orphan_keys": orphan_keys,
    }
